"""
Refresh Shreya's story list.

Run from the project folder:   python scripts/update_stories.py
It reads her author pages on Nepal Connect and The Annapurna Express
and rewrites assets/stories.js. Commit + push, and Vercel updates the site.
"""
import html, json, re, urllib.request, datetime, os
from concurrent.futures import ThreadPoolExecutor

UA = {"User-Agent": "Mozilla/5.0"}
NC_AUTHOR = "shreya-shrestha"
AE_AUTHOR_IDS = [877, 1294, 1180]   # 877 = her own byline, others = shared bylines

def get(url):
    req = urllib.request.Request(url, headers=UA)
    return urllib.request.urlopen(req, timeout=30).read().decode("utf-8", "replace")

def clean(s):
    s = re.sub(r"<[^>]+>", "", s)
    for _ in range(4):              # some summaries are escaped several times over
        s = html.unescape(s)
    return re.sub(r"\s+", " ", s.replace("\xa0", " ")).strip()

MONTHS = {m: i + 1 for i, m in enumerate(
    ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"])}

def ae_date(s):
    m = re.match(r"([A-Za-z]+)\.? (\d{1,2}), (\d{4})", s or "")
    if not m:
        return ""
    return datetime.date(int(m[3]), MONTHS[m[1][:3].lower()], int(m[2])).isoformat()

# ---- Nepal Connect ----
author = json.loads(get(f"https://nepalconnect.world/api/authors/by-slug/{NC_AUTHOR}"))
nc = []
for a in author["articles"]:
    v = json.loads(get("https://nepalconnect.world/api/articles/" + a["slug"]))
    v = v.get("article", v)
    nc.append(dict(
        url="https://nepalconnect.world/article/" + a["slug"],
        title=a["title"].strip(), type=a["type"], section=a["category"],
        date=a["published_at"][:10], excerpt=(v.get("excerpt") or "").strip(),
        img=v.get("image_url") or "", tags=[t["name"] for t in v.get("tags") or []]))

# ---- The Annapurna Express ----
ae, seen = [], set()
for aid in AE_AUTHOR_IDS:
    for page in range(1, 30):
        try:
            h = get(f"https://theannapurnaexpress.com/author/{aid}/?page={page}")
        except Exception:
            break
        found = 0
        for row in h.split("single__row-wrapper")[1:]:
            m = re.search(r'single__row-title.*?<a href="(/story/\d+/)">(.*?)</a>', row, re.S)
            by = re.search(r'href="/author/(\d+)/"\s+class="meta__separator post__meta-author">.*?<span>(.*?)</span>', row, re.S)
            if not m or not by or by[1] != str(aid):
                continue
            found += 1
            if m[1] in seen:
                continue
            seen.add(m[1])
            img = re.search(r'<img src="([^"]+)"', row)
            dt = re.search(r"([A-Z][a-z]{2,8}\.? \d{1,2}, \d{4})", row)
            ae.append(dict(url="https://theannapurnaexpress.com" + m[1], title=clean(m[2]),
                           img=img[1] if img else "", date=ae_date(dt[1] if dt else ""),
                           by=clean(by[2])))
        if not found:
            break

def details(x):
    try:
        h = get(x["url"])
    except Exception:
        x["excerpt"], x["section"] = "", ""
        return
    d = re.search(r'<meta (?:property|name)="og:description" content="(.*?)"', h, re.S)
    x["excerpt"] = clean(d[1])[:200] if d else ""
    i = h.find("BOOK REVIEW")
    cats = re.findall(r'/category/[^"]+"[^>]*>\s*([^<]+?)\s*<', h[i:]) if i >= 0 else []
    x["section"] = cats[0] if cats else ""

with ThreadPoolExecutor(10) as pool:
    list(pool.map(details, ae))
ae.sort(key=lambda x: x["date"], reverse=True)

data = dict(updated=datetime.date.today().isoformat(),
            bio=author.get("bio", ""), photo=author.get("photo_url", ""), nc=nc, ae=ae)
out = os.path.join(os.path.dirname(__file__), "..", "assets", "stories.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by scripts/update_stories.py — do not edit by hand.\n")
    f.write("window.STORIES = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"Saved {len(nc)} Nepal Connect + {len(ae)} Annapurna Express stories to assets/stories.js")
